/**
 * Server-side rules for public checkout (incident 20261118).
 *
 * POST /orders and POST /payments/process are public so visitors can buy, which means nothing in their bodies can
 * be trusted: the price comes from tbProducts, the amount charged comes from the stored order, and the legacy test
 * price (?Teste=1, orders.transaction.test.*) applies only to a staff caller or to a customer flagged
 * tbCustomers.TestUser = 1. The Banco Inter callback is public too, so it only ever confirms an order after asking
 * Banco Inter whether that order's own charge is paid.
 */

/** Price of a package row (tbProducts): promotional price, else normal price; null when not sellable. */
export function packagePrice(row: { NormalPrice?: any; PromotionalPrice?: any; Blocked?: any } | null | undefined): number | null {
  if (!row) return null;
  if (row.Blocked === true || Number(row.Blocked) === 1) return null;
  const normal = Number(row.NormalPrice) || 0;
  const promo = Number(row.PromotionalPrice) || normal;
  return promo > 0 ? Math.round(promo * 100) / 100 : null;
}

export interface ChargeInput {
  orderTotal: number;
  method: string;
  /** ?Teste=1 / ?BoletoTeste from the request body */
  testRequested: boolean;
  /** request e-mail equals tbConfig orders.transaction.test.email */
  emailMatchesTestEmail: boolean;
  /** verified staff token on the request, or the order's customer has TestUser = 1 */
  testAllowed: boolean;
  /** the order's customer has tbCustomers.TestUser = 1: always charged the test value (owner's own test account) */
  testUser?: boolean;
  testValue: number;
  testValueBoleto: number;
}

/** Smallest test charge Banco Inter accepts for boleto/PIX. */
export const MIN_TEST_VALUE_INTER = 2.5;
/** Smallest test charge used for Cielo card payments. */
export const MIN_TEST_VALUE_CARD = 1.0;

/** Amount to charge: the stored order total, or the test value when (and only when) testing is allowed. */
export function chargeAmount(i: ChargeInput): { amount: number; test: boolean } {
  if (i.testAllowed && (i.testRequested || i.emailMatchesTestEmail || i.testUser === true)) {
    const boletoPix = ['inter-boleto', 'pix'].includes(i.method);
    // Owner's floors: Banco Inter (boleto/PIX) does not issue below R$ 2,50; Cielo accepts R$ 1,00.
    const amount = boletoPix
      ? Math.max(i.testValueBoleto || 0, MIN_TEST_VALUE_INTER)
      : Math.max(i.testValue || 0, MIN_TEST_VALUE_CARD);
    return { amount, test: true };
  }
  return { amount: i.orderTotal, test: false };
}

const MAX_ORDER_ID = 2_147_483_647; // tbOrders.ID is int: a bigger "id" would make the lookup itself fail

/**
 * Cobrança v3 situacao values that cannot mean "paid". A callback item carrying one of them is not worth a bank call
 * (Inter also calls back when a boleto is issued, A_RECEBER). Anything else, or no situacao, is checked.
 */
const NOT_PAID_SITUACOES = new Set(['A_RECEBER', 'ATRASADO', 'CANCELADO', 'EXPIRADO', 'FALHA_EMISSAO', 'EM_PROCESSAMENTO', 'PROTESTO']);

/** One callback item: Cobrança v3 ({ codigoSolicitacao, seuNumero, situacao, txid, ... }) or PIX ({ txid, endToEndId, ... }). */
function callbackItems(body: any): any[] {
  const items: any[] = [];
  for (const b of Array.isArray(body) ? body : [body]) {
    if (!b || typeof b !== 'object') continue;
    if (Array.isArray(b.pix)) {
      for (const p of b.pix) if (p && typeof p === 'object') items.push(p);
      continue;
    }
    items.push(b);
  }
  return items.slice(0, 50);
}

const isCobrancaItem = (b: any) => b?.codigoSolicitacao != null || b?.seuNumero != null;
const skipBySituacao = (b: any) => typeof b?.situacao === 'string' && NOT_PAID_SITUACOES.has(b.situacao.toUpperCase());

/**
 * Order ids a Banco Inter callback refers to (Cobrança v3 seuNumero; for legacy PIX txids, their digits). Only
 * candidates: never trusted. The txid of a bolepix (inside a Cobrança item or in a PIX callback) is generated by
 * Inter and holds no order id, so it is not read as one.
 */
export function webhookOrderIds(body: any): number[] {
  const ids = new Set<number>();
  const add = (v: any) => {
    const s = String(v ?? '').trim();
    if (!/^\d{1,10}$/.test(s)) return;
    const n = parseInt(s, 10);
    if (n > 0 && n <= MAX_ORDER_ID) ids.add(n);
  };
  for (const b of callbackItems(body)) {
    if (isCobrancaItem(b)) {
      if (!skipBySituacao(b)) add(b.seuNumero);
      continue;
    }
    const m = typeof b.txid === 'string' ? b.txid.match(/(\d+)/) : null;
    if (m) add(m[1]);
  }
  return [...ids].slice(0, 20);
}

/** Payment identifiers named by a callback: Cobrança v3 codigoSolicitacao and PIX txids (tbOrders.Identifier). */
export function webhookIdentifiers(body: any): { codigos: string[]; pixTxids: string[] } {
  const codigos = new Set<string>();
  const pixTxids = new Set<string>();
  const ok = (v: any) => typeof v === 'string' && /^[A-Za-z0-9-]{1,100}$/.test(v);
  for (const b of callbackItems(body)) {
    if (isCobrancaItem(b)) {
      if (!skipBySituacao(b) && ok(b.codigoSolicitacao)) codigos.add(b.codigoSolicitacao);
    } else if (ok(b.txid)) {
      pixTxids.add(b.txid);
    }
  }
  return { codigos: [...codigos].slice(0, 20), pixTxids: [...pixTxids].slice(0, 20) };
}

type WebhookOrder = { id: number; statusId: number; paymentMethodId: number; paymentIdentifier: string | null };

export interface WebhookDeps {
  findOrder(id: number): Promise<WebhookOrder | null>;
  checkPix(txid: string): Promise<{ paid: boolean }>;
  checkBoleto(nossoNumero: string): Promise<{ paid: boolean }>;
  confirm(orderId: number, source: string): Promise<unknown>;
  /** Order whose tbOrders.Identifier is this codigoSolicitacao / txid. */
  findOrderByIdentifier?(identifier: string): Promise<WebhookOrder | null>;
  /**
   * Recent pending Banco Inter boleto orders. A PIX callback for a bolepix names only Inter's own txid, which is not
   * stored, so those orders are checked instead (each one against its own charge).
   */
  recentPendingBoletoOrderIds?(): Promise<number[]>;
}

/** PIX orders carry FormaPagamento 2 (same rule as GET /payments/status). */
export const PIX_PAYMENT_METHOD_ID = 2;

/** Candidate orders of a callback, in order: by identifier, by seuNumero/txid digits, then the bolepix sweep. */
async function candidateIds(body: any, deps: WebhookDeps): Promise<number[]> {
  const ids = new Set<number>();
  const { codigos, pixTxids } = webhookIdentifiers(body);
  let unresolvedPix = false;
  if (deps.findOrderByIdentifier) {
    for (const c of codigos) {
      const o = await deps.findOrderByIdentifier(c);
      if (o) ids.add(o.id);
    }
    for (const t of pixTxids) {
      const o = await deps.findOrderByIdentifier(t);
      if (o) ids.add(o.id);
      else unresolvedPix = true;
    }
  } else {
    unresolvedPix = pixTxids.length > 0;
  }
  for (const id of webhookOrderIds(body)) ids.add(id);
  if (unresolvedPix && deps.recentPendingBoletoOrderIds) {
    for (const id of (await deps.recentPendingBoletoOrderIds()).slice(0, 30)) ids.add(id);
  }
  return [...ids];
}

/**
 * Confirms only the orders whose own charge Banco Inter reports as paid. The payload decides which orders to look
 * at, never whether they are paid. Returns the confirmed ids.
 */
export async function confirmVerifiedOrders(body: any, deps: WebhookDeps): Promise<number[]> {
  const confirmed: number[] = [];
  for (const id of await candidateIds(body, deps)) {
    try {
      const order = await deps.findOrder(id);
      if (!order || !order.paymentIdentifier || order.statusId >= 2) continue;
      const status = order.paymentMethodId === PIX_PAYMENT_METHOD_ID
        ? await deps.checkPix(order.paymentIdentifier)
        : await deps.checkBoleto(order.paymentIdentifier);
      if (status?.paid) {
        await deps.confirm(order.id, 'webhook:banco-inter:verified');
        confirmed.push(order.id);
      }
    } catch {
      // one failing lookup or bank call never stops the other orders of the callback; polling retries it
    }
  }
  return confirmed;
}
